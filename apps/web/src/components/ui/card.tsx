import * as React from "react"

import { cn } from "@/lib/utils"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        // Base: white card, large rounded corners, subtle shadow, no harsh border
        "group/card flex flex-col gap-0 overflow-hidden rounded-2xl bg-white text-sm text-card-foreground shadow-sm",
        "data-[size=sm]:gap-0 data-[size=sm]:rounded-xl",
        className
      )}
      {...props}
    />
  )
}

